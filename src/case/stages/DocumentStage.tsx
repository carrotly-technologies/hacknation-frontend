import { Check, FileDown, FileText, Printer } from 'lucide-react'
import type { ReactNode } from 'react'
import { Link } from 'react-router'
import type { SheetFormat } from '../../api/cases'
import { DeadlineText } from '../../components/Deadline'
import { Button, ButtonLink, Card, InfoList, InfoRow, InlineAlert } from '../../components/ui'
import { useCaseAction, useSheetDownload } from '../../lib/caseQueries'
import { fmtDate } from '../../lib/format'
import { allows, caseUrl, STAGE_SHORT } from '../../lib/stages'
import { SheetDocument } from '../../sheet/SheetDocument'
import type { StageProps } from '../CasePage'
import { AckLinkSection } from './AckLinkSection'
import s from './DocumentStage.module.css'
import { StageError, StageLayout } from './StageLayout'
import layout from './StageLayout.module.css'

/**
 * Last step, "Ocena końcowa": where the signed assessment stands (signature, handover, acknowledgement and the
 * objection deadline computed by the API), the link for the assessed person, the filled sheet to download (PDF and
 * DOCX generated by the API) or print, and its preview.
 */
export function DocumentStage({ detail, model, criteria, stage }: StageProps) {
  const info = detail.stages.find((x) => x.id === stage)!
  const act = useCaseAction(detail.id)
  const isFirst = detail.path === 'FIRST'
  const signed = detail.signedByEvaluatorOn
  // SEND_FOR_ACK stays available after the handover (it generates a new link), so the date decides.
  const sentOn = detail.sentForAckOn ?? null
  const sent = !!sentOn || !!detail.acknowledgedOn
  const acked = detail.acknowledgedOn
  const nextCycle = detail.history.filter((h) => h.text.startsWith('Nowy cykl')).at(-1)
  const signStage = isFirst ? 'FIRST_CONDITIONS' : 'JUSTIFICATION'
  const ackLabel = isFirst
    ? 'Oceniany zapoznał się z pierwszą oceną'
    : (criteria.sheet?.template?.employeeAcknowledgement ?? 'Oceniany zapoznał się z oceną okresową')

  const status = acked ? (
    <InlineAlert tone={isFirst ? 'success' : 'info'} title={`Oceniany zapoznał się z oceną ${fmtDate(acked)}`}>
      {isFirst && <p>Pierwsza ocena jest zakończona. Przełożony kieruje wniosek do dyrektora generalnego (art. 38 ust. 3 ustawy).</p>}
      {detail.objectionDeadline?.date && <p>Termin na sprzeciw mija {fmtDate(detail.objectionDeadline.date)}.</p>}
      {nextCycle && <p>{nextCycle.text}</p>}
    </InlineAlert>
  ) : sent ? (
    <InlineAlert tone="warning" title={`Ocena przekazana do zapoznania${sentOn ? ` ${fmtDate(sentOn)}` : ''}`}>
      Oceniany jeszcze nie potwierdził, że zapoznał się z oceną.
    </InlineAlert>
  ) : signed ? (
    <InlineAlert tone="success" title={`Ocena podpisana ${fmtDate(signed)}`}>
      Przekaż ocenę ocenianemu do zapoznania: wygeneruj dla niego link poniżej.
    </InlineAlert>
  ) : (
    <InlineAlert tone="warning" title="Ocena nie jest jeszcze podpisana">
      Podpisz ocenę w kroku <Link to={caseUrl(detail.id, signStage)}>„{STAGE_SHORT[signStage]}”</Link>. Do tego czasu
      pobrany arkusz jest wersją roboczą.
    </InlineAlert>
  )

  return (
    <StageLayout info={info} status={status}>
      <Card title="Stan procesu" as="h3">
        <InfoList>
          <InfoRow label="Podpis oceniającego" value={<Done on={signed} />} />
          <InfoRow label="Przekazanie do zapoznania" value={<Done on={sentOn} done={sent} />} />
          <InfoRow label="Zapoznanie ocenianego" value={<Done on={acked} />} />
          {!isFirst && (
            <InfoRow
              label="Termin na sprzeciw"
              value={
                detail.objectionDeadline ? (
                  <DeadlineText deadline={detail.objectionDeadline} />
                ) : (
                  <span className={layout.muted}>od dnia zapoznania</span>
                )
              }
            />
          )}
        </InfoList>
        {!isFirst && detail.objectionDeadline && <p className={s.legal}>Termin na sprzeciw: {detail.objectionDeadline.legalBasis}</p>}
      </Card>

      <Card title="Zapoznanie ocenianego z oceną" as="h3">
        <div className={s.stack}>
          <AckLinkSection detail={detail} label={ackLabel} />
          {sent && !acked && (
            <>
              <p className={layout.muted}>
                W wersji demonstracyjnej możesz zasymulować potwierdzenie ocenianego. Datą zapoznania będzie dzisiejsza data.
              </p>
              <div className={s.buttons}>
                <Button
                  variant="secondary"
                  loading={act.isPending}
                  disabled={!allows(detail, 'EMPLOYEE_ACK_ASSESSMENT')}
                  onClick={() => act.mutate('EMPLOYEE_ACK_ASSESSMENT')}
                >
                  Oceniany zapoznał się z oceną (symulacja)
                </Button>
              </div>
            </>
          )}
          <StageError error={act.error} />
        </div>
      </Card>

      <SheetFiles caseId={detail.id} periodic={!isFirst} signed={!!signed} />

      <Card title="Podgląd arkusza" as="h3">
        <div className={s.paper} role="region" aria-label="Podgląd arkusza" tabIndex={0}>
          <SheetDocument detail={detail} model={model} criteria={criteria} />
        </div>
      </Card>
    </StageLayout>
  )
}

/** "✓ 16.11.2026" when done, "jeszcze nie" otherwise. */
function Done({ on, done = !!on }: { on: string | null | undefined; done?: boolean }) {
  if (!done) return <span className={layout.muted}>jeszcze nie</span>
  return (
    <span className={s.done}>
      <Check size={16} aria-hidden="true" className={s.check} />
      {on ? fmtDate(on) : 'tak'}
    </span>
  )
}

/** Download (PDF, DOCX from the API) and print. The first assessment has no file yet: printing only. */
function SheetFiles({ caseId, periodic, signed }: { caseId: string; periodic: boolean; signed: boolean }) {
  const { download, pending, error } = useSheetDownload(caseId)
  const fileButton = (format: SheetFormat, label: string, icon: ReactNode) => (
    <Button
      variant={format === 'pdf' ? 'primary' : 'secondary'}
      icon={icon}
      loading={pending === format}
      disabled={pending !== undefined}
      onClick={() => download(format)}
    >
      {label}
    </Button>
  )
  return (
    <Card title="Arkusz oceny" as="h3">
      <div className={s.stack}>
        <p className={layout.muted}>
          {periodic
            ? 'Pobierz wypełniony arkusz jako PDF (do archiwum i wydruku) albo DOCX (do edycji w Wordzie lub LibreOffice) albo wydrukuj go z przeglądarki.'
            : 'Wydrukuj wypełniony arkusz z przeglądarki. W oknie drukowania możesz też zapisać go jako PDF.'}
          {periodic && !signed && ' Przed podpisem oceniającego pobrany plik ma oznaczenie „WERSJA ROBOCZA”.'}
        </p>
        <div className={s.buttons}>
          {periodic && fileButton('pdf', 'Pobierz PDF', <FileDown size={18} aria-hidden="true" />)}
          {periodic && fileButton('docx', 'Pobierz DOCX', <FileText size={18} aria-hidden="true" />)}
          <ButtonLink variant={periodic ? 'secondary' : 'primary'} icon={<Printer size={18} aria-hidden="true" />} to={`/teczka/${caseId}/arkusz?druk=1`}>
            Drukuj
          </ButtonLink>
        </div>
        {error && (
          <InlineAlert tone="error" live title="Nie udało się pobrać arkusza">
            {error.message} Spróbuj ponownie za chwilę.
          </InlineAlert>
        )}
      </div>
    </Card>
  )
}
